ALTER TABLE public.roles ADD COLUMN is_public boolean NOT NULL DEFAULT false;
ALTER TABLE public.volunteer_badges ADD COLUMN is_public boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN public.roles.is_public IS 'Administrator-approved publication flag; new role definitions are private by default.';
COMMENT ON COLUMN public.volunteer_badges.is_public IS 'Administrator-approved publication flag; new badge definitions are private by default.';
UPDATE public.roles SET is_public = true WHERE code::text IN ('USER','NOMINEE','AMBASSADOR','OLC_COORDINATOR','NRC','JURY','SPONSOR','ADMIN','SUPER_ADMIN');
UPDATE public.volunteer_badges SET is_public = true WHERE code IN ('ambassador','bronze','chapter_coordinator','continental','founding','gold','lead','silver','verified');
ALTER TABLE public.roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.volunteer_badges ENABLE ROW LEVEL SECURITY;
DROP POLICY "Roles are public" ON public.roles;
DROP POLICY "Public view badges" ON public.volunteer_badges;
CREATE POLICY "Read approved role definitions" ON public.roles FOR SELECT TO anon, authenticated USING (is_public = true);
CREATE POLICY "Administrators manage role definitions" ON public.roles FOR ALL TO authenticated USING (public.has_role(auth.uid(), 'admin'::public.app_role)) WITH CHECK (public.has_role(auth.uid(), 'admin'::public.app_role));
CREATE POLICY "Read approved badge definitions" ON public.volunteer_badges FOR SELECT TO anon, authenticated USING (is_public = true);
REVOKE ALL ON public.roles FROM anon, authenticated;
REVOKE ALL ON public.volunteer_badges FROM anon, authenticated;
GRANT SELECT ON public.roles TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.roles TO authenticated;
GRANT ALL ON public.roles TO service_role;
GRANT SELECT ON public.volunteer_badges TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.volunteer_badges TO authenticated;
GRANT ALL ON public.volunteer_badges TO service_role;